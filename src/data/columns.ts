export function getColumnBySlug(slug: string): Column | undefined {
  return COLUMNS.find((col) => col.slug === slug);
}

export function getAllCategories(): string[] {
  const categories = COLUMNS.map((col) => col.category);
  return Array.from(new Set(categories));
}

export function getRelatedColumns(currentSlug: string, limit: number = 3): Column[] {
  const current = getColumnBySlug(currentSlug);
  if (!current) return COLUMNS.slice(0, limit);

  // 同じカテゴリの記事を優先し、足りなければ他の記事で埋める
  const sameCategory = COLUMNS.filter(
    (col) => col.slug !== currentSlug && col.category === current.category
  );
  const otherCategory = COLUMNS.filter(
    (col) => col.slug !== currentSlug && col.category !== current.category
  );

  return [...sameCategory, ...otherCategory].slice(0, limit);
}
